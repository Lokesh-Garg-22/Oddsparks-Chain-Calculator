/**
 * Pure helpers for icon download: which wiki file to use, checking a download really is a PNG,
 * and the credits page. No network or file access.
 */
import { normalizeTitle } from './wikitext.mjs';
import { esc } from './report.mjs';

/**
 * Wiki files to try, best first: the image its page's infobox shows (recorded by the extractor),
 * then the recipe template's convention ("Sawn timber.png"), then the name as written.
 * @param {string} name
 * @param {string | null} image e.g. "File:Arty spark large.png"
 */
export function candidateFiles(name, image) {
  const out = [image, `File:${normalizeTitle(`${name.toLowerCase()}.png`)}`, `File:${normalizeTitle(`${name}.png`)}`];
  return [...new Set(out.filter((f) => f !== null))];
}

const PNG_SIGNATURE = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];

/** True if the bytes start with the PNG signature (guards against error pages saved as icons). @param {Uint8Array} b */
export function looksLikePng(b) {
  return PNG_SIGNATURE.every((v, i) => b[i] === v);
}

/**
 * site/icons/CREDITS.md
 * @param {{ name: string, path: string, file: string, pageUrl: string, uploader: string }[]} rows
 * @param {string[]} missing names with no icon on the wiki
 */
export function renderCredits(rows, missing) {
  return [
    '# Icon credits',
    '',
    '**The icons are game artwork from Oddsparks: An Automation Adventure, © THQ Nordic AB.** They are not covered by this project\'s MIT licence, nor by the CC BY-SA licence of the game data, and the wiki records no other licence for them. They are used here, as on the Oddsparks Wiki, to identify items and buildings in a fan-made, non-commercial tool. If the rights holder objects, they will be removed; the calculator works without them (it shows names instead).',
    '',
    'Each icon is a 128 px copy of the file uploaded to the [Oddsparks Wiki](https://oddsparks.wiki.gg) by the user listed. Generated by `tools/download-icons.mjs`; do not edit by hand.',
    '',
    '| Name | Icon | Wiki file | Uploaded by |',
    '|---|---|---|---|',
    ...rows.toSorted((a, b) => a.path.localeCompare(b.path))
      .map((r) => `| ${esc(r.name)} | \`${r.path}\` | [${esc(r.file)}](${r.pageUrl}) | ${esc(r.uploader)} |`),
    '',
    `## No icon on the wiki (${missing.length})`,
    '',
    ...(missing.length ? missing.toSorted().map((m) => `- ${esc(m)}`) : ['None.']),
    '',
  ].join('\n');
}
