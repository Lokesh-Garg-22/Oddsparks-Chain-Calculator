// @ts-check
/** Render the extraction report (site/data/extraction-report.md) for a human to review. */

const WIKI = 'https://oddsparks.wiki.gg/wiki/';
/** Wiki text is editable by anyone: escape it so it can't add links, HTML or formatting to the report. */
export const esc = (/** @type {unknown} */ v) => String(v).replace(/[\\`*_{}[\]()#+!|<>~]/g, '\\$&');
const link = (/** @type {string} */ page) => `[${esc(page)}](${WIKI}${encodeURIComponent(page.replace(/ /g, '_'))})`;

/**
 * @param {ReturnType<typeof import('./build.mjs').buildDataset>} result
 */
export function renderReport({ data, report }) {
  const c = data.meta.counts;
  const itemName = (/** @type {string} */ id) => data.items[id]?.name ?? id;
  /** "inputs.raw-aether.amount" → "amount of Raw Aether (input)" */
  const describe = (/** @type {string} */ path) => {
    const [kind, item, field] = path.split('.');
    return item ? `${field} of ${esc(itemName(item))} (${kind === 'inputs' ? 'input' : 'output'})` : path;
  };
  const value = (/** @type {string} */ path, /** @type {unknown} */ v) => (path.endsWith('.odds') && typeof v === 'number' ? `${Math.round(v * 1000) / 10}%` : esc(v));
  const recipesWhere = (/** @type {(r: any) => boolean} */ test) => Object.entries(data.recipes).filter(([, r]) => test(r));

  const lines = [
    '# Extraction report',
    '',
    `Generated by \`tools/extract-wiki.mjs\` from the Oddsparks Wiki on ${data.meta.extractedAt}. Data version \`${data.meta.dataVersion}\`.`,
    'Review this after every extraction. Fixes go in `overrides.json` with a source, never in `oddsparks.json`.',
    '',
    '## Summary',
    '',
    '| | Count |',
    '|---|---|',
    `| Pages with recipes | ${report.recipePages} |`,
    `| Recipe blocks read | ${report.blocks} |`,
    `| Recipes after merging copies | ${c.recipes} |`,
    `| Recipes whose copies disagree | ${c.recipesWithConflicts} |`,
    `| Recipes missing a value on every page | ${c.recipesWithProblems} |`,
    `| Recipes found on only one page | ${c.recipesFromOnePage} |`,
    `| Buildings | ${c.buildings} |`,
    `| Items | ${c.items} |`,
    '',
  ];

  /** @param {string} title @param {string} why @param {string[]} body @param {number} [count] */
  const section = (title, why, body, count = body.length) => {
    lines.push(`## ${title} (${count})`, '', why, '');
    lines.push(...(body.length ? body : ['None.']), '');
  };

  const conflicted = recipesWhere((r) => Object.keys(r.conflicts).length > 0);
  section('Conflicts', 'Copies of the same recipe state different values. The value most pages state is used; a tie goes to the building\'s own page; for fuel, any "yes" wins. Check in-game and record the answer in `overrides.json`.',
    conflicted.flatMap(([id, r]) => [
      `- **${id}**`,
      ...Object.entries(r.conflicts).map(([path, said]) => `  - ${describe(path)}: ${/** @type {any[]} */ (said).map((s) => `${link(s.page)} says ${value(path, s.value)}`).join(' · ')}`),
    ]), conflicted.length);

  const missing = recipesWhere((r) => r.problems.length > 0);
  section('Missing values', 'A needed value isn\'t stated (readably) on any page. Shown with a warning in the app until fixed.',
    missing.flatMap(([id, r]) => [`- **${id}**`, ...r.problems.map((/** @type {string} */ p) => `  - ${esc(p)}`)]), missing.length);

  section('Unreadable values', 'Written on a page but not understood. Harmless when another copy states the value; worth fixing on the wiki.',
    report.unreadable.map((u) => `- ${link(u.page)}: ${esc(u.message)}`));

  section('Same name, different ingredients or products', 'One building, one recipe name, but the pages list different items. Usually a copy-paste error on one page, sometimes real variants. Check in-game.',
    report.sameNameDifferentItems.map((s) => `- **${esc(s.name)}** (${s.building}): ${s.ids.map((id) => {
      const r = data.recipes[id];
      const list = (/** @type {{ amount: number | null, item: string }[]} */ l) => l.map((x) => `${x.amount} ${esc(itemName(x.item))}`).join(' + ') || 'nothing';
      return `\`${id}\` ${list(r.inputs)} → ${list(r.outputs)} (${link(r.sources[0].page)})`;
    }).join(' · ')}`));

  section('Possible duplicates', 'Same building and items, written on different pages under different names. If they are one recipe, list them in `mergeRecipes` in `overrides.json`. Differing numbers can mean a modifier is already applied on one page (e.g. overclocking).',
    report.possibleDuplicates.map(({ ids, numbersAgree }) => `- ${ids.map((id) => `\`${id}\` (${data.recipes[id].duration} s, ${link(data.recipes[id].sources[0].page)})`).join(' vs ')}${numbersAgree ? '' : '. Numbers differ'}`));

  section('Names spelled differently on different pages', 'Merged as one recipe because the numbers agree and the names differ by only a few letters. The building page\'s spelling is used.',
    report.nameVariants.map((v) => `- \`${v.id}\`: ${v.names.map((n) => `"${esc(n)}"`).join(', ')}`));

  section('Name changes', 'Names written differently from their page title (letter case or a redirect). The page title is used. A redirect can mean the game renamed the item.',
    report.renames.map((r) => `- "${esc(r.from)}" → "${esc(r.to)}"`));

  section('Id collisions', 'Different names that produce the same id. The second one was merged into the first: fix the extractor or the wiki.',
    report.slugCollisions.map((s) => `- \`${s.id}\`: ${s.names.map((n) => `"${esc(n)}"`).join(', ')}`));

  section('Items without a wiki page', 'May be typos, renamed items or simply undocumented.', report.missingPages.map((n) => `- ${esc(n)}`));

  section('Ingredients nothing makes', 'Treated as raw resources unless a recipe is added.', report.neverProduced.map((id) => `- ${esc(itemName(id))}`));

  section('Buildings not on the Buildings page', 'Non-standard buildings. Never chosen as the default recipe unless overrides say so.', report.notOnBuildingsPage.map((n) => `- ${link(n)}`));

  section('Skipped blocks', 'Recipe blocks that could not be used at all.', report.skipped.map((p) => `- ${link(p.page)}: ${esc(p.message)}`));

  section('Unknown template fields', 'The wiki template may have new fields the extractor ignores. Teach `tools/wiki/build.mjs` about them if they matter.',
    Object.entries(report.unknownFields).map(([k, pages]) => `- ${esc(k)} on ${pages.map(link).join(', ')}`));

  section('Values with leftover markup', 'Cleaned values that still contain wiki markup.', report.leftoverMarkup.map((m) => `- ${link(m.page)}: ${esc(m.value)}`));

  const filled = recipesWhere((r) => Object.keys(r.valueFrom).length > 0);
  section('Values taken from another page', 'The building\'s own page doesn\'t state these (or is outvoted); the value comes from another copy.',
    filled.map(([id, r]) => `- \`${id}\`: ${Object.entries(r.valueFrom).map(([path, page]) => `${describe(path)} from ${link(/** @type {string} */ (page))}`).join(' · ')}`));

  const single = recipesWhere((r) => r.sources.length === 1).map(([id]) => `\`${id}\``);
  section('Recipes found on only one page', 'No second copy to cross-check against.', single.length ? [single.join(', ')] : [], single.length);

  return lines.join('\n');
}
